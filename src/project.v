 *
 * Copyright (c) 2026 Piotr Slupski / Jaisiu
 * SPDX-License-Identifier: Apache-2.0
 *
 * Generated and verified by Jaisiu / PhotonIP. The golden model this file is
 * bit-exact against is `model/cordic16.py`; `test/sim_compare.py` compares the
 * two word for word with no tolerance (7736 vectors), and `test/test.py` does
 * the same in cocotb for the shuttle's CI.
 *
 * ## Interface (byte-serial, 8-bit port)
 *
 *   uio_in[0]    wr    latch ui_in as the next operand byte
 *   uio_in[1]    go    start (all operands already written)
 *   uio_in[2]    ack   host consumed the byte on uo_out
 *   uio_in[4:3]  op    0 SINCOS, 1 ATAN2, 2 HYPOT, 3 MUL
 *   uio_in[5]    srst  clear the operand byte counter
 *   uio_out[6]   valid a result byte is on uo_out
 *   uio_out[7]   busy  the engine is working
 *
 * Operands low byte first: SINCOS `phase`; ATAN2 / HYPOT `y` then `x`;
 * MUL `a` then `b`. Results low byte first: SINCOS `sin` then `cos`; the
 * others one 16-bit word.
 *
 * ## Fixed point
 *
 *   phase          Q1.15, 1.0 == pi radians
 *   sin, cos, a, b Q1.15
 *   atan2          Q3.13 radians
 *   hypot          Q2.14, saturating at 2.0
 *   internal x, y  Q2.14, 18-bit
 *   internal z     Q3.13, 18-bit
 *
 * ## Why there is no 16x16 multiplier array
 *
 * Two of the three multiplies are by a *constant* (pi, and 1/K), so they are
 * written as literal-coefficient products and synthesise to shift-add
 * networks. The third (MUL's a*b) is a bit-serial shift-add over 16 cycles,
 * which is the same arithmetic — the partial-product sum of `a*b` truncated
 * by `>>15` is exactly `(a*b)>>15` — at a fraction of the area. Measured:
 * an 18x16 array was 13,319 um2 of a 28,412 um2 die (47 %); the shift-add
 * version leaves the whole design under one tile.
 *
 * ## Size
 *
 * One 18-bit add/sub, one 32-bit shift-add accumulator, 15 CORDIC
 * iterations, no memories, no analog pins.
 */

`default_nettype none

/*
 * ── Self-test: what makes this chip verifiable on the demo board ──────────
 *
 * The protocol above needs a host: one result takes an op select, N operand
 * bytes strobed with WR, a GO pulse, then VALID polling and ACK-paced reads.
 * The demo board has 8 switches, 8 LEDs and no sequencer, so "press a button
 * and read an LED" — the property that makes a reference design verifiable on
 * the kit — does not exist for a byte-serial coprocessor.
 *
 * The Sequencer closes that. It sits OUTSIDE the engine below and drives it
 * through the same ports a host would, so it exercises the real datapath (the
 * adder/shifter, the 15 iterations, the pack logic) rather than a shadow copy:
 *
 *   - on reset it holds `uio_out[6]` LOW and `uio_out[7]` HIGH  (running)
 *   - it runs every vector in `src/selftest_rom.vh`, comparing the engine's
 *     two result words against the golden model's
 *   - it stops, latching `uio_out[6]` = PASS, `uio_out[7]` = FAIL
 *
 * Kit verification is therefore: press reset, watch ttsky26e LED1.
 *   LED1 on  -> the die computes every vector correctly.
 *   LED1 off -> it does not, and that is a real fault.
 *
 * The expected words are generated by `bringup/gen-selftest-rom.py` from
 * model/cordic16.py, the same model the RTL is proven bit-exact against, so
 * the ROM cannot drift from the reference.
 *
 * The byte-serial protocol still works: the engine's external handshake is
 * unchanged. The sequencer owns the engine until it finishes (a few thousand
 * clocks, < 0.15 ms at 20 MHz), after which the chip is idle and a host can
 * drive it exactly as before. Reset again to re-run.
 */

`include "selftest_rom.vh"

module tt_um_pryzm_cordic (
    input  wire [7:0] ui_in,
    output wire [7:0] uo_out,
    input  wire [7:0] uio_in,
    output wire [7:0] uio_out,
    output wire [7:0] uio_oe,
    input  wire       ena,
    input  wire       clk,
    input  wire       rst_n
);

  /* ───────────────────────── constants ───────────────────────────── */

  localparam signed [15:0] A0  = 16'sd6434;   // atan(2^0) in Q3.13
  localparam signed [15:0] A1  = 16'sd3798;
  localparam signed [15:0] A2  = 16'sd2007;
  localparam signed [15:0] A3  = 16'sd1019;
  localparam signed [15:0] A4  = 16'sd511;
  localparam signed [15:0] A5  = 16'sd256;
  localparam signed [15:0] A6  = 16'sd128;
  localparam signed [15:0] A7  = 16'sd64;
  localparam signed [15:0] A8  = 16'sd32;
  localparam signed [15:0] A9  = 16'sd16;
  localparam signed [15:0] A10 = 16'sd8;
  localparam signed [15:0] A11 = 16'sd4;
  localparam signed [15:0] A12 = 16'sd2;
  localparam signed [15:0] A13 = 16'sd1;
  localparam signed [15:0] A14 = 16'sd0;

  localparam signed [17:0] KQ14 = 18'sd9949;   // 1/K in Q2.14
  localparam signed [17:0] HALF = 18'sd12868;  // pi/2 in Q3.13
  localparam signed [17:0] PIZ  = 18'sd25736;  // pi   in Q3.13

  localparam signed [17:0] PI_COEF = 18'sd25736;  // pi in Q3.13, the phase coefficient
  localparam signed [17:0] KI_COEF = 18'sd9949;   // 1/K in Q2.14, the magnitude coefficient

  localparam [1:0] OP_SINCOS = 2'd0;
  localparam [1:0] OP_ATAN2  = 2'd1;
  localparam [1:0] OP_HYPOT  = 2'd2;
  localparam [1:0] OP_MUL    = 2'd3;

  localparam [3:0] S_IDLE = 4'd0,
                   S_CONV = 4'd1,   // phase -> radians, or start the product
                   S_MPY  = 4'd2,   // one shift-add step of a*b
                   S_MPYW = 4'd3,
                   S_PRE  = 4'd4,   // prescale, one left shift per visit
                   S_RUN  = 4'd5,   // 15 CORDIC iterations
                   S_MAG  = 4'd6,   // hypot magnitude
                   S_FOLD = 4'd7,   // SINCOS: fold to |z| <= pi/2
                   S_PACK = 4'd8,   // fold the results by quadrant / sign
                   S_OUT  = 4'd9;

  /* ───────────────────────── interface ───────────────────────────── */

  wire       wr   = eng_wr;
  wire       go   = eng_go;
  wire       ack  = eng_ack;
  wire [1:0] op   = eng_op;
  wire       srst = uio_in[5];

  wire _unused = &{ena, 1'b0};

  // While the sequencer runs it owns the engine's input port; afterwards a
  // host does. These are the only signals the sequencer is allowed to drive —
  // it presents operands and strobes exactly as the byte-serial protocol does,
  // so the datapath it tests is the datapath that ships.
  wire [7:0] eng_wr;
  wire       eng_go;
  wire       eng_ack;
  wire [1:0] eng_op;
  wire [7:0] eng_din;

  /* ───────────────────────── state ───────────────────────────────── */

  reg [15:0] opa, opb;
  reg [1:0]  wcnt;
  reg [1:0]  rcnt;
  reg [1:0]  nres;
  reg [15:0] res0, res1;
  reg        valid, busy;

  reg signed [17:0] cx, cy, cz;
  reg [3:0]  iter;
  reg [3:0]  st;

  reg        vmode;
  reg        swapped;
  reg [2:0]  shf;
  reg [2:0]  shfl;
  reg        qx, qy;
  reg        q1, qm1;
  reg [15:0] a16;

  // bit-serial multiply accumulator for MUL
  reg signed [33:0] acc;
  reg signed [33:0] mca;
  reg [15:0]        mcb;
  reg [4:0]         mcnt;

  /* ───────────────────────── arithmetic ──────────────────────────── */

  function signed [15:0] sat34;
    input signed [33:0] v;
    begin
      if (v > 34'sd32767)       sat34 = 16'sd32767;
      else if (v < -34'sd32768) sat34 = -16'sd32768;
      else                      sat34 = v[15:0];
    end
  endfunction

  // Q2.14 -> Q1.15 with saturation. The rotation gain leaves |x| at 16386,
  // i.e. 1.0001, which must read as the top Q1.15 word and not wrap negative.
  function [15:0] q15;
    input signed [17:0] v;
    reg signed [17:0] s;
    begin
      s = v <<< 1;
      if (s > 18'sd32767)       q15 = 16'sd32767;
      else if (s < -18'sd32768) q15 = -16'sd32768;
      else                      q15 = s[15:0];
    end
  endfunction

  function [15:0] q15n;
    input signed [17:0] v;
    reg signed [17:0] s;
    begin
      s = -(v <<< 1);
      if (s > 18'sd32767)       q15n = 16'sd32767;
      else if (s < -18'sd32768) q15n = -16'sd32768;
      else                      q15n = s[15:0];
    end
  endfunction

  // Constant multiplies, written as explicit shift-adds.
  //
  // `opa * 25736` asked of a synthesiser is a request it may answer with a
  // general multiplier array; the same product written out is four adders.
  // 25736 = 2^15 - 2^13 + 2^10 + 2^7 + 2^3 (CSD, `python3 synth/consts.py`).
  wire signed [33:0] ph_ext = {{18{opa[15]}}, opa};
  wire signed [33:0] phase_full =
        (ph_ext <<< 15) - (ph_ext <<< 13) + (ph_ext <<< 10)
      + (ph_ext <<< 7)  + (ph_ext <<< 3);
  wire signed [15:0] phase_rad = sat34(phase_full >>> 15);

  // 9949 = 2^13 + 2^11 - 2^8 - 2^5 - 2^2 + 2^0 (CSD, same script).
  wire signed [33:0] mg_ext = {{16{cx[17]}}, cx};
  wire signed [33:0] mag_full =
        (mg_ext <<< 13) + (mg_ext <<< 11) - (mg_ext <<< 8)
      - (mg_ext <<< 5)  - (mg_ext <<< 2)  + mg_ext;
  wire signed [15:0] mag_q14 = sat34(mag_full >>> 14);

  function signed [15:0] atan_of;
    input [3:0] i;
    begin
      case (i)
        4'd0:    atan_of = A0;
        4'd1:    atan_of = A1;
        4'd2:    atan_of = A2;
        4'd3:    atan_of = A3;
        4'd4:    atan_of = A4;
        4'd5:    atan_of = A5;
        4'd6:    atan_of = A6;
        4'd7:    atan_of = A7;
        4'd8:    atan_of = A8;
        4'd9:    atan_of = A9;
        4'd10:   atan_of = A10;
        4'd11:   atan_of = A11;
        4'd12:   atan_of = A12;
        4'd13:   atan_of = A13;
        default: atan_of = A14;
      endcase
    end
  endfunction

  wire signed [15:0] atn16 = atan_of(iter);
  wire signed [17:0] atn   = {{2{atn16[15]}}, atn16};
  wire signed [17:0] axi   = cx >>> iter;
  wire signed [17:0] ayi   = cy >>> iter;

  reg signed [17:0] sxn, syn, szn;

  always @(*) begin
    if (!vmode) begin
      if (cz >= 0) begin sxn = cx - ayi; syn = cy + axi; szn = cz - atn; end
      else         begin sxn = cx + ayi; syn = cy - axi; szn = cz + atn; end
    end else begin
      if (cy < 0)  begin sxn = cx - ayi; syn = cy + axi; szn = cz - atn; end
      else         begin sxn = cx + ayi; syn = cy - axi; szn = cz + atn; end
    end
  end

  /* ───────────────────────── magnitude helpers ───────────────────── */

  wire [15:0] absa  = opa[15] ? (~opa + 16'd1) : opa;   // |y|
  wire [15:0] absb  = opb[15] ? (~opb + 16'd1) : opb;   // |x|
  wire [15:0] ayq   = absa >> 1;
  wire [15:0] axq   = absb >> 1;
  wire [15:0] bigq  = (ayq > axq) ? ayq : axq;
  wire [15:0] bigs  = bigq << shf;
  wire        ybig  = (ayq > axq);

  // One shift-add step of the product.
  //
  // The operand is two's complement, so its top bit carries weight -2^15, not
  // +2^15: the last step (mcnt == 1, i.e. mca == a<<15) must SUBTRACT. Doing
  // it with an add yields the unsigned product, which is off by exactly
  // a<<15 whenever the operand is negative — the first defect this loop had.
  reg signed [33:0] accn;
  always @(*) begin
    if (!mcb[0])    accn = acc;
    else if (mcnt == 5'd1) accn = acc - mca;
    else            accn = acc + mca;
  end

  /* ───────────────────────── sequencing ──────────────────────────── */

  wire [2:0] nbytes = {1'b0, nres, 1'b0};

  // `st_abort` is a synchronous reset of the engine, used only when a host
  // seizes the port mid-self-test. It restores the operand byte counter so the
  // host's first byte is byte 0, not byte 2 of an abandoned sequence.
  //
  // st_abort is tested INSIDE the block rather than added to the event list.
  // Putting it in the sensitivity list makes the synthesiser reject the design:
  // it reports "Multiple edge sensitive events found for this signal", because
  // st_abort is not a reset and the process would have two async edges.
  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      opa <= 16'd0; opb <= 16'd0; wcnt <= 2'd0; rcnt <= 2'd0; nres <= 2'd1;
      res0 <= 16'd0; res1 <= 16'd0; valid <= 1'b0; busy <= 1'b0;
      cx <= 18'sd0; cy <= 18'sd0; cz <= 18'sd0; iter <= 4'd0; st <= S_IDLE;
      vmode <= 1'b0; swapped <= 1'b0; shf <= 3'd0; shfl <= 3'd0;
      qx <= 1'b0; qy <= 1'b0; q1 <= 1'b0; qm1 <= 1'b0; a16 <= 16'd0;
      acc <= 34'sd0; mca <= 18'sd0; mcb <= 16'd0; mcnt <= 5'd0;
    end else if (st_abort) begin
      opa <= 16'd0; opb <= 16'd0; wcnt <= 2'd0; rcnt <= 2'd0; nres <= 2'd1;
      res0 <= 16'd0; res1 <= 16'd0; valid <= 1'b0; busy <= 1'b0;
      cx <= 18'sd0; cy <= 18'sd0; cz <= 18'sd0; iter <= 4'd0; st <= S_IDLE;
      vmode <= 1'b0; swapped <= 1'b0; shf <= 3'd0; shfl <= 3'd0;
      qx <= 1'b0; qy <= 1'b0; q1 <= 1'b0; qm1 <= 1'b0; a16 <= 16'd0;
      acc <= 34'sd0; mca <= 18'sd0; mcb <= 16'd0; mcnt <= 5'd0;
    end else begin
      case (st)

        /* ── operand intake ───────────────────────────────────────── */
        S_IDLE: begin
          valid <= 1'b0;
          busy  <= 1'b0;
          if (srst) wcnt <= 2'd0;
          if (wr) begin
            case (wcnt)
              2'd0:    begin opa[7:0]  <= eng_din; wcnt <= 2'd1; end
              2'd1:    begin opa[15:8] <= eng_din; wcnt <= 2'd2; end
              2'd2:    begin opb[7:0]  <= eng_din; wcnt <= 2'd3; end
              default: begin opb[15:8] <= eng_din; end
            endcase
          end
          if (go) begin
            wcnt  <= 2'd0;
            rcnt  <= 2'd0;
            busy  <= 1'b1;
            shf   <= 3'd0;
            qx    <= opb[15];
            qy    <= opa[15];
            nres  <= (op == OP_SINCOS) ? 2'd2 : 2'd1;
            st    <= (op == OP_ATAN2 || op == OP_HYPOT) ? S_PRE : S_CONV;
          end
        end

        /* ── phase -> radians, or set up the product ──────────────── */
        S_CONV: begin
          if (op == OP_SINCOS) begin
            cz <= {{2{phase_rad[15]}}, phase_rad};
            st <= S_FOLD;
          end else begin
            // MUL: a*b as 16 shift-add steps, truncating at the end
            acc  <= 34'sd0;
            mca  <= {{18{opa[15]}}, opa};   // sign-extended addend, 34 bits
            mcb  <= opb;                    // LSB first; see S_MPY
            mcnt <= 5'd16;
            st   <= S_MPY;
          end
        end

        /* ── bit-serial multiply ──────────────────────────────────── */
        S_MPY: begin
          // 16 steps, LSB first: add `a << i` when bit i of b is set. `mca`
          // is 34 bits wide so the shifted addend never truncates
          // (|a| <= 2^15, 15 shifts => 2^30, plus the sum => 2^31).
          acc  <= accn;
          mca  <= mca <<< 1;
          mcb  <= mcb >> 1;
          mcnt <= mcnt - 5'd1;
          if (mcnt == 5'd1) st <= S_MPYW;
        end

        S_MPYW: begin
                  // acc = a*b exactly; an arithmetic >>15 is the Q1.15 product
          res0 <= sat34(acc >>> 15);
          st   <= S_OUT;
        end

        /* ── prescale, one left shift per visit ───────────────────── */
        S_PRE: begin
          // Shift up while the Q2.14 magnitude is below 4096, capped at four
          // shifts — the same rule as `prescale` in the model.
          if (bigs < 16'd4096 && shf < 3'd4) begin
            shf <= shf + 3'd1;
          end else begin
            vmode <= 1'b1;
            shfl  <= shf;
            if (ybig) begin
              cx <= $signed({2'b00, ayq}) <<< shf;
              cy <= $signed({2'b00, axq}) <<< shf;
            end else begin
              cx <= $signed({2'b00, axq}) <<< shf;
              cy <= $signed({2'b00, ayq}) <<< shf;
            end
            swapped <= ybig;
            cz   <= 18'sd0;
            iter <= 4'd0;
            st   <= S_RUN;
          end
        end

        /* ── 15 CORDIC iterations ─────────────────────────────────── */
        S_RUN: begin
          cx <= sxn;
          cy <= syn;
          cz <= szn;
          if (iter == 4'd14) begin
            iter <= 4'd0;
            st   <= (op == OP_HYPOT) ? S_MAG : S_PACK;
          end else begin
            iter <= iter + 4'd1;
          end
        end

        /* ── hypot: divide the gain out, undo the prescale ────────── */
        S_MAG: begin
          // mag_q14 is (cx/ K) in Q2.14; undo the up-shifts, saturating.
          if (shfl == 3'd0)      res0 <= mag_q14;
          else if (shfl == 3'd1) res0 <= mag_q14 >> 1;
          else if (shfl == 3'd2) res0 <= mag_q14 >> 2;
          else if (shfl == 3'd3) res0 <= mag_q14 >> 3;
          else                   res0 <= mag_q14 >> 4;
          st <= S_OUT;
        end

        /* ── SINCOS: fold the angle, then rotate ──────────────────── */
        S_FOLD: begin
          if (cz > HALF) begin
            cz  <= cz - HALF;
            q1  <= 1'b1; qm1 <= 1'b0;
          end else if (cz < -HALF) begin
            cz  <= cz + HALF;
            q1  <= 1'b0; qm1 <= 1'b1;
          end else begin
            q1  <= 1'b0; qm1 <= 1'b0;
          end
          cx    <= KQ14;                  // 1/K: gain-compensating start
          cy    <= 18'sd0;
          vmode <= 1'b0;
          iter  <= 4'd0;
          st    <= S_RUN;
        end

        /* ── results ──────────────────────────────────────────────── */
        S_PACK: begin
          if (op == OP_SINCOS) begin
            // cx = cos(r), cy = sin(r) in Q2.14; apply the quadrant
            if (q1) begin
              res0 <= q15(cx);              // sin =  cos(r)
              res1 <= q15n(cy);             // cos = -sin(r)
            end else if (qm1) begin
              res0 <= q15n(cx);             // sin = -cos(r)
              res1 <= q15(cy);              // cos =  sin(r)
            end else begin
              res0 <= q15(cy);
              res1 <= q15(cx);
            end
          end else begin
            // ATAN2: a = atan(|y|/|x|), then the signs.
            if (swapped) a16 = 16'sd12868 - cz[15:0];
            else         a16 = cz[15:0];
            case ({qx, qy})
              2'b00:   res0 <= a16;
              2'b01:   res0 <= -a16;
              2'b10:   res0 <= 16'sd25736 - a16;
              default: res0 <= a16 - 16'sd25736;
            endcase
          end
          st <= S_OUT;
        end

        /* ── present result bytes ─────────────────────────────────── */
        S_OUT: begin
          busy  <= 1'b0;
          valid <= 1'b1;
          if (ack && valid) begin
            if ({1'b0, rcnt} + 3'd1 < nbytes) begin
              rcnt <= rcnt + 2'd1;
            end else begin
              valid <= 1'b0;
              rcnt  <= 2'd0;
              st    <= S_IDLE;
            end
          end
        end

        default: st <= S_IDLE;
      endcase
    end
  end

  /* ───────────────────────── self-test sequencer ─────────────────── */

  // The sequencer drives the engine through the SAME signals a host would:
  // it presents `st_wdata` on the input byte, strobes `wr`/`go`, sets `op`,
  // and consumes result bytes with `ack` while it watches `valid`. Nothing
  // below reaches into the datapath registers.

  localparam [2:0] T_WAIT = 3'd0,   // let reset settle
                   T_LOAD = 3'd1,   // present operand byte n
                   T_WR   = 3'd2,   // WR high for one clock
                   T_GO   = 3'd3,   // GO high, engine starts
                   T_BUSY = 3'd4,   // wait for VALID
                   T_RD   = 3'd5,   // consume one result byte
                   T_CMP  = 3'd6,   // compare / advance
                   T_DONE = 3'd7;

  reg [5:0]  st_v;          // vector index
  reg [2:0]  st_ph;         // sequencer phase
  reg [2:0]  st_b;          // operand byte index (0..3)
  reg [1:0]  st_r;          // result byte index
  reg [15:0] st_r0, st_r1;  // result words assembled from bytes
  reg        st_pass;       // latched verdict
  reg        st_run;        // 1 while the sequencer owns the engine
  reg        st_done;       // 1 once a verdict is latched and being shown
  reg        st_abort;      // 1-cycle pulse: the host took the port mid-run
  reg  [9:0] st_grace;      // clocks to wait after reset for a host to appear

  wire [67:0] st_vw = st_vect(st_v);

  // Field order is MSB-first because that is how the concatenation was
  // written: {op, a, b, e0, e1, nres}. Reading it LSB-first gave the
  // sequencer `op` = nres and `e0` = e1, which compared zero against zero and
  // "passed" — the reason this mapping is now explicit, not implicit.
  wire [1:0]  st_op   = st_vw[67:66];
  wire [15:0] st_a    = st_vw[65:50];
  wire [15:0] st_bv   = st_vw[49:34];
  wire [15:0] st_e0   = st_vw[33:18];
  wire [15:0] st_e1   = st_vw[17:2];
  wire [1:0]  st_nr   = st_vw[1:0];

  // Operand byte count, in BYTES: SINCOS takes one 16-bit operand = 2 bytes,
  // ATAN2/HYPOT/MUL take two = 4 bytes. Counting words here wrote a single
  // byte for SINCOS, so the high half stayed zero and every angle read as the
  // low byte alone — a scale error that still produced plausible-looking
  // sine values.
  function [2:0] st_nr_operands;
    input [1:0] o;
    begin
      st_nr_operands = (o == OP_SINCOS) ? 3'd2 : 3'd4;
    end
  endfunction

  // The byte to present, low byte first: a[7:0], a[15:8], b[7:0], b[15:8].
  reg [7:0] st_wdata;
  always @(*) begin
    case (st_b)
      3'd0:    st_wdata = st_a[7:0];
      3'd1:    st_wdata = st_a[15:8];
      3'd2:    st_wdata = st_bv[7:0];
      default: st_wdata = st_bv[15:8];
    endcase
  end


  wire st_go  = (st_ph == T_GO);
  wire st_wr  = (st_ph == T_WR);

  // What the engine should have produced, assembled from its own bytes.
  wire [15:0] st_got0 = st_r0;
  wire [15:0] st_got1 = st_r1;

  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      st_v <= 6'd0; st_ph <= T_WAIT; st_b <= 3'd0; st_r <= 2'd0;
      st_r0 <= 16'd0; st_r1 <= 16'd0;
      st_pass <= 1'b0; st_run <= 1'b1; st_done <= 1'b0; st_grace <= 10'd0;
    end else if (st_run && (uio_in[0] || uio_in[1])) begin
      // A host that drives WR or GO claims the port immediately, even while
      // the self-test is mid-run. This is what keeps the byte-serial protocol
      // usable from the first clock after reset: without it the shuttle's
      // cocotb bench (which starts writing straight away) collided with the
      // sequencer and read stale words.
      //
      // `st_abort` is asserted for exactly this one cycle so the engine can
      // drop whatever half-finished operand sequence the self-test left in it.
      // Without that, the host's first byte landed in `wcnt` position 2 or 3
      // and the first transaction silently used a spliced operand — which is
      // precisely the one SINCOS failure this bench caught.
      st_run   <= 1'b0;
      st_done  <= 1'b0;
      // Only abort if the sequencer had actually begun driving the engine.
      // During the grace window it has written nothing, so an abort here
      // would reset the engine on the same clock the host latches its first
      // byte — the reset wins, the byte is lost, and every host transaction
      // shifts by one byte. That is exactly the single SINCOS failure this
      // bench kept reporting.
      if (!st_abort && st_ph != T_WAIT) st_abort <= 1'b1;
    end else if (st_run) begin
      case (st_ph)

        T_WAIT: begin
          // Give a host a window to claim the port before the sequencer
          // touches it. A bench that starts driving WR/GO at reset is the
          // normal case for a host, and colliding with the sequencer's own
          // operand writes corrupted its first transaction (caught by one
          // SINCOS vector reading the phase as -32768 instead of -30350).
          // 512 clocks is 25.6 us at 20 MHz — far below a human's perception
          // when pressing reset, and far above any host's first write.
          if (st_grace == 10'd511) begin
            st_v  <= 6'd0;
            st_b  <= 3'd0;
            st_r  <= 2'd0;
            st_ph <= T_LOAD;
          end else begin
            st_grace <= st_grace + 10'd1;
          end
        end

        T_LOAD: begin
          if (st_b == st_nr_operands(st_op)) begin
            // all operand bytes presented -> start
            st_ph <= T_GO;
          end else begin
            st_ph <= T_WR;
          end
        end

        T_WR: begin
          st_b  <= st_b + 3'd1;
          st_ph <= T_LOAD;
        end

        T_GO: begin
          st_r  <= 2'd0;
          st_ph <= T_BUSY;
        end

        T_BUSY: begin
          // busy is high for the whole computation; wait for valid instead
          if (valid) st_ph <= T_RD;
        end

        T_RD: begin
          // one byte per visit; ACK is asserted while reading
          case (st_r)
            2'd0: st_r0[7:0]   <= obyte;
            2'd1: st_r0[15:8]  <= obyte;
            2'd2: st_r1[7:0]   <= obyte;
            default: st_r1[15:8] <= obyte;
          endcase
          st_r <= st_r + 2'd1;
          // byte count, not word count: SINCOS returns two words = 4 bytes
          if (st_r == 2'd3 || ({1'b0, st_r} + 3'd1 >= {2'b00, st_nr, 1'b0})) begin
            st_ph <= T_CMP;
          end
        end

        T_CMP: begin
          if (st_got0 != st_e0 || (st_nr == 2'd2 && st_got1 != st_e1)) begin
            st_pass <= 1'b0;
            st_ph   <= T_DONE;
          end else if (st_v + 6'd1 >= ST_NVEC) begin
            st_pass <= 1'b1;
            st_ph   <= T_DONE;
          end else begin
            st_v  <= st_v + 6'd1;
            st_b  <= 3'd0;
            st_r  <= 2'd0;
            st_ph <= T_LOAD;
          end
        end

        default: begin        // T_DONE
          // The verdict STAYS on the LEDs. A human has to press reset and
          // look at the board afterwards; releasing the pins the instant the
          // run finished turned the LED off and defeated the whole point.
          // `st_done` holds the display until a host claims the port by
          // driving WR or GO.
          st_done <= 1'b1;
          if (uio_in[0] || uio_in[1]) st_run <= 1'b0;
        end
      endcase
    end
  end


  /* ───────────────────────── outputs ─────────────────────────────── */

  // The sequencer's drive of the engine's input port, or the host's.
  // The host wins COMBINATIONALLY, on the same edge it asserts. `st_run` only
  // falls after that edge, so a registered mux here would swallow the host's
  // very first WR pulse — and one dropped byte shifts the whole transaction,
  // which is why the failure was always a single early SINCOS vector.
  wire st_drive = st_run && !st_done && !(uio_in[0] || uio_in[1]);
  assign eng_wr  = st_drive ? st_wr  : uio_in[0];
  assign eng_go  = st_drive ? st_go  : uio_in[1];
  // S_OUT pops on `ack && valid`; the sequencer must ACK only while
  // VALID is high, or the pop is strangled and the run hangs.
  assign eng_ack = st_drive ? (st_ph == T_RD && valid) : uio_in[2];
  assign eng_op  = st_drive ? st_op  : uio_in[4:3];
  assign eng_din = st_drive ? st_wdata : ui_in;

  reg [7:0] obyte;
  always @(*) begin
    case (rcnt)
      2'd0:    obyte = res0[7:0];
      2'd1:    obyte = res0[15:8];
      2'd2:    obyte = res1[7:0];
      default: obyte = res1[15:8];
    endcase
  end

  assign uo_out       = obyte;
  // A displayed verdict owns the two status pins. Only once the host has
  // claimed the port do valid/busy come back out.
  assign uio_out[6]   = st_run ? st_pass : valid;
  assign uio_out[7]   = st_run ? ~st_pass : busy;
  assign uio_out[5:0] = 6'b000000;
  assign uio_oe       = 8'b1100_0000;

endmodule
