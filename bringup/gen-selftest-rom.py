#!/usr/bin/env python3
"""Generate the self-test vector ROM for src/project.v.

The Sequencer this feeds is what makes the die verifiable on the demo board
with no host attached: on reset it runs these vectors against the real
datapath and leaves the verdict on uo_out.

The expected words are computed by `model/cordic16.py` — the same model
`test/sim_compare.py` and the cocotb bench compare the RTL against — so the
ROM cannot drift from the reference. Nothing here is hand-typed.

    python3 bringup/gen-selftest-rom.py           # -> src/selftest_rom.vh
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "model"))

import cordic16 as M  # noqa: E402

OP_SINCOS, OP_ATAN2, OP_HYPOT, OP_MUL = 0, 1, 2, 3

# Corners first: these are where a broken datapath fails, and they are the
# vectors a human will reason about while watching the LED.
PHASES = [-32768, -24576, -16384, -8192, -1, 0, 1, 8192, 16384, 24576, 32767]
PAIRS = [
    (-32767, -32767), (-32767, 32767), (32767, -32767), (32767, 32767),
    (0, 32767), (32767, 0), (0, -32768), (-32768, 0),
    (1, 1), (16384, 16384), (-100, 250),
]
MULS = [
    (0, 0), (1, 32767), (-1, 32767), (32767, 32767), (-32768, -32768),
    (16384, 2), (-1234, 5678), (256, -256),
]


def vectors():
    out = []
    for ph in PHASES:
        sn, cs = M.sincos(ph)
        out.append((OP_SINCOS, ph & 0xFFFF, 0, sn & 0xFFFF, cs & 0xFFFF, 2))
    for y, x in PAIRS:
        out.append((OP_ATAN2, y & 0xFFFF, x & 0xFFFF,
                    M.atan2(y, x) & 0xFFFF, 0, 1))
        out.append((OP_HYPOT, y & 0xFFFF, x & 0xFFFF,
                    M.hypot(y, x) & 0xFFFF, 0, 1))
    for a, b in MULS:
        out.append((OP_MUL, a & 0xFFFF, b & 0xFFFF,
                    M.mul(a, b) & 0xFFFF, 0, 1))
    return out


def emit(vecs, path):
    lines = []
    lines.append("// GENERATED by bringup/gen-selftest-rom.py — do not edit.")
    lines.append("// Expected words come from model/cordic16.py, the same model the")
    lines.append("// RTL is proven bit-exact against. %d vectors." % len(vecs))
    lines.append("")
    lines.append("localparam [5:0] ST_NVEC = 6'd%d;" % len(vecs))
    lines.append("")
    lines.append("// {op[1:0], a[15:0], b[15:0], e0[15:0], e1[15:0], nres[1:0]} = 68 bits")
    lines.append("function [67:0] st_vect;")
    lines.append("  input [4:0] i;")
    lines.append("  begin")
    for n, (op, a, b, e0, e1, nres) in enumerate(vecs):
        lines.append("    case (i)")
        break
    for n, (op, a, b, e0, e1, nres) in enumerate(vecs):
        lines.append("      6'd%-2d: st_vect = {2'd%d, 16'd%d, 16'd%d, 16'd%d, 16'd%d, 2'd%d};"
                     % (n, op, a, b, e0, e1, nres))
    lines.append("      default: st_vect = {2'd0, 16'd0, 16'd0, 16'd0, 16'd0, 2'd1};")
    lines.append("    endcase")
    lines.append("  end")
    lines.append("endfunction")
    lines.append("")
    open(path, "w").write("\n".join(lines) + "\n")


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--corrupt", action="store_true",
                    help="flip one expected bit, to prove the sequencer can FAIL")
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "selftest_rom.vh"))
    a = ap.parse_args()
    vecs = vectors()
    if a.corrupt:
        op, av, bv, e0, e1, nres = vecs[5]
        vecs[5] = (op, av, bv, e0 ^ 0x0001, e1, nres)
    out = a.out
    emit(vecs, out)
    print("%d vectors -> %s" % (len(vecs), out))
    for n, v in enumerate(vecs[:4]):
        print("  %2d op=%d a=%5d b=%5d e0=%5d" % (n, v[0], M.s16(v[1]), M.s16(v[2]), M.s16(v[3])))


if __name__ == "__main__":
    main()
